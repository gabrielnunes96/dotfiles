#!/usr/bin/env python3
"""Hide, disable or rename sound cards, like the sound panel on other systems.

Writes WirePlumber 0.4 rules to ~/.config/wireplumber/main.lua.d/51-audio-devices.lua
and restarts WirePlumber. A card can be fully disabled, kept as output only or as
input only (a microphone with a headphone jack stops showing up as an output), and
get a friendlier name in the sound applet.
"""
import json
import subprocess
from pathlib import Path

import gi

gi.require_version("Gtk", "3.0")
gi.require_version("Gdk", "3.0")
from gi.repository import Gdk, Gtk  # noqa: E402

HOME = Path.home()
STATE = HOME / ".config/audio-devices/devices.json"
WP_DIR = HOME / ".config/wireplumber"
RULES = WP_DIR / "main.lua.d/51-audio-devices.lua"
PROFILE_SETS = WP_DIR / "profile-sets"
DEFAULT_SET = Path("/usr/share/alsa-card-profile/mixer/profile-sets/default.conf")

BOTH, OUTPUT, INPUT, OFF = "both", "output", "input", "off"
LABELS = {BOTH: "Saída e entrada", OUTPUT: "Só saída", INPUT: "Só entrada", OFF: "Desativado"}


def load_state():
    try:
        return json.loads(STATE.read_text())
    except (OSError, ValueError):
        return {}


def current_cards():
    """Cards PipeWire sees now: name -> {orig, has_out, has_in}."""
    out = subprocess.run(["pactl", "-f", "json", "list", "cards"],
                         capture_output=True, text=True).stdout
    cards = {}
    for c in json.loads(out or "[]"):
        if not c["name"].startswith("alsa_card."):
            continue
        profiles = c.get("profiles", {})
        desc = c["properties"].get("device.description") or c["name"]
        cards[c["name"]] = {
            "orig": desc,
            "has_out": any("output:" in p for p in profiles),
            "has_in": any("input:" in p for p in profiles),
        }
    return cards


def filtered_profile_set(direction):
    """default.conf keeping only the mappings for one direction."""
    keep, drop = ("paths-input", "paths-output") if direction == INPUT else ("paths-output", "paths-input")
    lines, section, body = ["[General]", "auto-profiles = yes", ""], None, []

    def flush():
        if section is None:
            return
        keys = {l.split("=")[0].strip(): l.split("=", 1)[1].strip() for l in body if "=" in l}
        has = keep in keys
        pathless = "paths-input" not in keys and "paths-output" not in keys
        wanted = has or (direction == OUTPUT and pathless and keys.get("direction") != "input")
        if not wanted:
            return
        lines.append(section)
        lines.extend(l for l in body if not l.startswith((drop, "direction")))
        lines.extend([f"direction = {direction}", ""])

    for raw in DEFAULT_SET.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith((";", "#")):
            continue
        if line.startswith("["):
            flush()
            section, body = (line, []) if line.startswith("[Mapping ") else (None, [])
        elif section:
            body.append(line)
    flush()
    return "\n".join(lines) + "\n"


def lua(s):
    return json.dumps(s, ensure_ascii=False)


def write_rules(state):
    PROFILE_SETS.mkdir(parents=True, exist_ok=True)
    sets = {}
    for d in (INPUT, OUTPUT):
        p = PROFILE_SETS / f"{d}-only.conf"
        p.write_text(filtered_profile_set(d))
        sets[d] = str(p)

    out = ["-- generated by audio-devices; edit it through that app", ""]
    for name, info in sorted(state.items()):
        props = {}
        if info["mode"] == OFF:
            props["device.disabled"] = True
        elif info["mode"] in (INPUT, OUTPUT):
            props["device.profile-set"] = sets[info["mode"]]
        if info.get("name"):
            props["device.description"] = info["name"]
        if props:
            out.append("table.insert(alsa_monitor.rules, {")
            out.append(f'  matches = {{ {{ {{ "device.name", "equals", {lua(name)} }} }} }},')
            out.append("  apply_properties = {")
            out += [f"    [{lua(k)}] = {lua(v) if not isinstance(v, bool) else str(v).lower()},"
                    for k, v in props.items()]
            out += ["  },", "})", ""]
        if info.get("name") and info["mode"] != OFF:
            # sinks and sources keep the old name unless renamed too
            for kind in ("output", "input"):
                out.append("table.insert(alsa_monitor.rules, {")
                out.append(f'  matches = {{ {{ {{ "node.name", "matches", "alsa_{kind}.{name[len("alsa_card."):]}*" }} }} }},')
                out.append(f'  apply_properties = {{ ["node.description"] = {lua(info["name"])} }},')
                out += ["})", ""]
    RULES.parent.mkdir(parents=True, exist_ok=True)
    RULES.write_text("\n".join(out))


class App(Gtk.Window):
    def __init__(self):
        super().__init__(title="Dispositivos de áudio")
        self.set_default_size(680, -1)
        self.set_position(Gtk.WindowPosition.CENTER)
        self.connect("key-press-event", self.on_key)

        bar = Gtk.HeaderBar(title="Dispositivos de áudio", show_close_button=True)
        bar.set_subtitle("ocultar, desativar ou renomear")
        self.set_titlebar(bar)

        state = load_state()
        live = current_cards()
        self.rows = {}
        names = sorted(set(state) | set(live),
                       key=lambda n: (state.get(n, {}).get("mode") == OFF, n not in live, n))

        box = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=12, margin=16)
        listbox = Gtk.ListBox(selection_mode=Gtk.SelectionMode.NONE)
        listbox.get_style_context().add_class("frame")
        for name in names:
            # a renamed card reports the new name, so the saved original wins
            info = {**live.get(name, {}), **state.get(name, {})}
            info.update({k: live[name][k] for k in ("has_out", "has_in") if name in live})
            info.setdefault("mode", BOTH)
            info.setdefault("orig", name)
            listbox.add(self.make_row(name, info, name in live))
        box.pack_start(listbox, False, False, 0)

        hint = Gtk.Label(xalign=0, wrap=True)
        hint.set_markup("<small>Nome vazio mantém o original. Ao aplicar, o som é "
                        "reiniciado (um segundo de silêncio).</small>")
        hint.get_style_context().add_class("dim-label")
        box.pack_start(hint, False, False, 0)

        buttons = Gtk.Box(spacing=8, halign=Gtk.Align.END)
        reset = Gtk.Button(label="Mostrar todos")
        reset.connect("clicked", self.on_reset)
        apply = Gtk.Button(label="Aplicar")
        apply.get_style_context().add_class("suggested-action")
        apply.connect("clicked", self.on_apply)
        buttons.pack_start(reset, False, False, 0)
        buttons.pack_start(apply, False, False, 0)
        box.pack_start(buttons, False, False, 0)
        self.add(box)

    def make_row(self, name, info, present):
        row = Gtk.ListBoxRow(activatable=False)
        grid = Gtk.Box(spacing=12, margin=10)
        icon = "audio-input-microphone" if info.get("has_in") and not info.get("has_out") \
            else "audio-card"
        grid.pack_start(Gtk.Image.new_from_icon_name(icon, Gtk.IconSize.DND), False, False, 0)

        texts = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=2)
        entry = Gtk.Entry(text=info.get("name", ""), placeholder_text=info["orig"],
                          width_chars=28)
        sub = Gtk.Label(xalign=0)
        note = "" if present else " · desconectado ou desativado"
        sub.set_markup(f"<small>{GLib_escape(info['orig'])}{note}</small>")
        sub.get_style_context().add_class("dim-label")
        texts.pack_start(entry, False, False, 0)
        texts.pack_start(sub, False, False, 0)
        grid.pack_start(texts, True, True, 0)

        combo = Gtk.ComboBoxText(valign=Gtk.Align.CENTER)
        has_out, has_in = info.get("has_out", True), info.get("has_in", True)
        modes = [BOTH, OUTPUT, INPUT, OFF] if has_out and has_in else [BOTH, OFF]
        for m in modes:
            label = LABELS[m] if m != BOTH or (has_out and has_in) else "Ativo"
            combo.append(m, label)
        combo.set_active_id(info["mode"] if info["mode"] in modes else BOTH)
        grid.pack_start(combo, False, False, 0)

        row.add(grid)
        self.rows[name] = (entry, combo, info)
        return row

    def on_key(self, _w, ev):
        if ev.keyval == Gdk.KEY_Escape:
            self.destroy()

    def on_reset(self, _b):
        for entry, combo, _ in self.rows.values():
            entry.set_text("")
            combo.set_active_id(BOTH)

    def on_apply(self, _b):
        state = {}
        for name, (entry, combo, info) in self.rows.items():
            state[name] = {
                "orig": info["orig"], "name": entry.get_text().strip(),
                "mode": combo.get_active_id(),
                "has_out": info.get("has_out", True), "has_in": info.get("has_in", True),
            }
        STATE.parent.mkdir(parents=True, exist_ok=True)
        STATE.write_text(json.dumps(state, indent=2, ensure_ascii=False))
        write_rules(state)
        subprocess.run(["systemctl", "--user", "restart", "wireplumber"])
        self.destroy()


def GLib_escape(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


if __name__ == "__main__":
    win = App()
    win.connect("destroy", Gtk.main_quit)
    win.show_all()
    Gtk.main()
